// ── Shared microcopy for deterministic routes ───────────────────────────────
// These keep Eli's voice identical on the routes that do NOT call the LLM
// (confirmations, summaries, no-data, safety) without duplicating wording.

// Deterministic, varied pick so repeated confirmations/openers don't read as
// canned. Rotates by a caller-supplied seed (e.g. an entry count or timestamp)
// or at random when no seed is given.
function pick(list, seed) {
  if (!Array.isArray(list) || list.length === 0) return '';
  const i =
    typeof seed === 'number' && Number.isFinite(seed)
      ? Math.abs(Math.trunc(seed)) % list.length
      : Math.floor(Math.random() * list.length);
  return list[i];
}

